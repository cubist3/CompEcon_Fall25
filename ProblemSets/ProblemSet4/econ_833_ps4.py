""" Keep: male heads, age 25–60, hourly wage > $7; create: ln(wage), Educ, Age, Age2, race dummies
    New Data Frame incl. following vars + cleaning raws: ln(wage), Educ, Age, Age2, Black, Hispanic, OtherRace, year """

def clean_raw(df, min_age=25, max_age=60, min_wage=7.0):

    # keep only vars that we will use for Q3
    tempDF = df[[ 'hlabinc', 'hannhrs', 'hsex', 'hrace', 'age', 'hyrsed', YEAR_COL ]].copy()
    tempDF = tempDF.rename(columns={YEAR_COL: 'year'})

    # ensure numeric for variables that will be used for regression
    for k in ['hlabinc', 'hannhrs', 'hsex', 'hrace', 'age', 'hyrsed', 'year']:
        tempDF[k] = pd.to_numeric(tempDF[k], errors='coerce')

    # hourly wage (drop non+ hours/income)
    tempDF = tempDF[(tempDF['hannhrs']>0) & (tempDF['hlabinc']>0)]
    tempDF['wage'] = tempDF['hlabinc'] / tempDF['hannhrs']

    tempDF = tempDF[tempDF['hsex'] == 1] # male heads: hsex == 1
    tempDF = tempDF[(tempDF['age'] >= min_age) & (tempDF['age'] <= max_age)] # age 25–60
    tempDF = tempDF[tempDF['wage'] > float(min_wage)] # wage > $7/hr

    # drop NA, missings
    tempDF = tempDF.dropna(subset=['wage', 'hyrsed', 'age', 'hrace', 'year'])

    # Q3 variables
    out = pd.DataFrame()
    out['lnw']  = np.log(tempDF['wage'])
    out['Educ'] = tempDF['hyrsed']
    out['Age'] = tempDF['age']
    out['Age2'] = tempDF['age'] ** 2
    out['year'] = tempDF['year'].astype(int)

    # hrace: 1=White, 2=Black, 3=Native American, 4=Asian/PI, 5=Hispanic, 6/7=Other
    out['Black']     = np.where(tempDF['hrace'] == 2, 1, 0)
    out['Hispanic']  = np.where(tempDF['hrace'] == 5, 1, 0)
    out['OtherRace'] = np.where(tempDF['hrace'].isin([3, 4, 6, 7]), 1, 0)

    out = out.dropna().reset_index(drop=True)
    return out

