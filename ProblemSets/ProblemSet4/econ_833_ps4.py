def check_b(df):
    """ ensure binary coding for race & across obs - race coding should be mutually exclusive"""
    for col in ['Black','Hispanic','OtherRace']:
        bad_vals = set(df[col].unique()) - {0, 1}
        assert len(bad_vals) == 0, f"{col} error: {bad_vals}"
    row_sum = df[['Black','Hispanic','OtherRace']].sum(axis=1)
    assert ((row_sum == 0) | (row_sum == 1)).all(), "error"
    print("Q2(b) unit test passed")

