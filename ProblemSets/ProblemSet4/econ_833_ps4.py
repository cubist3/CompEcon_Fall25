def mle_loglik(residuals):
    """ log-likelihood MLE: sigma^2_hat = RSS / n, logLik = -n/2 * [ln(2π) + 1 + ln(RSS/n)]"""
    n = residuals.size
    rss = np.sum(residuals**2)
    sig2 = rss / n
    return -0.5 * n * (np.log(2*np.pi) + 1 + np.log(sig2))

