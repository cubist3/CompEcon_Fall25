import numpy as np
import statsmodels.api as sm
from scipy.optimize import minimize

def _neg_loglike_linear(theta, X, y):
    k = X.shape[1]
    beta   = theta[:k]
    logsig = theta[k]
    sigma  = np.exp(logsig)
    r = y - X @ beta
    n = y.size
    return 0.5*n*np.log(2*np.pi) + n*logsig + 0.5*np.sum((r/sigma)**2)

def mle_linear_normal(X, y, method="L-BFGS-B"):
    X = np.asarray(X, float); y = np.asarray(y, float)
    n, k = X.shape
    # OLS init
    beta0 = np.linalg.lstsq(X, y, rcond=None)[0]
    resid = y - X @ beta0
    sig0  = np.sqrt(max(np.mean(resid**2), 1e-12))
    x0    = np.r_[beta0, np.log(sig0)]
    bounds = [(None, None)]*k + [(np.log(1e-8), np.log(1e8))]
    opt = minimize(_neg_loglike_linear, x0, args=(X, y), method=method, bounds=bounds)
    if not opt.success:
        raise RuntimeError("MLE not converge: " + opt.message)
    th = opt.x
    return th[:k], np.exp(th[k])

def test_mle_vs_ols(clean_df, years=(1971,1980,1990,2000), tol=1e-6):
    Xcols = ["const","Educ","Age","Age2","Black","Hispanic","OtherRace"]
    for yr in years:
        d = clean_df[clean_df["year"]==yr].copy()
        if d.empty:
            print(f"[{yr}] no rows — skipping."); continue
        d["const"] = 1.0
        X = d[Xcols].to_numpy()
        y = d["lnw"].to_numpy()

        ols = sm.OLS(y, X, missing="drop").fit()
        beta_ols = np.asarray(ols.params)

        beta_mle, sigma_mle = mle_linear_normal(X, y, method="L-BFGS-B")
        diff = np.max(np.abs(beta_mle - beta_ols))
        print(f"[{yr}] max|β_MLE-β_OLS|={diff:.2e}, σ_MLE={sigma_mle:.4f}")
        assert diff < tol, f"Year {yr}: MLE and OLS differ by {diff:.2e} ≥ {tol}"
    print("verified that : MLE matches OLS for all years")

test_mle_vs_ols(clean)

